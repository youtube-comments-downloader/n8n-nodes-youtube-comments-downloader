import fs from "node:fs"
import path from "node:path"
import { fileURLToPath } from "node:url"

import { buildReleaseNotes } from "./release-notes-lib.mjs"

const [latestVersion, version] = process.argv.slice(2)

if (!latestVersion || !version) {
  throw new Error("Usage: node scripts/update-changelog.mjs <latestVersion> <version>")
}

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const changelogPath = path.resolve(__dirname, "../CHANGELOG.md")
const changelog = fs.readFileSync(changelogPath, "utf8")
const section = buildReleaseNotes({
  version,
  from: latestVersion,
  to: "HEAD",
  format: "changelog",
})

const marker = "Generated by [`auto-changelog`](https://github.com/CookPete/auto-changelog).\n"

if (!changelog.includes(marker)) {
  throw new Error("Could not find changelog insertion marker.")
}

const updated = changelog.replace(marker, `${marker}\n${section}`)

fs.writeFileSync(changelogPath, updated)
